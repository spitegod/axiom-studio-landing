const words = (value: string) =>
  value
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .split(/\s+/)
    .filter(Boolean).length;

export function landingWordCount(page: LandingPageData): number {
  const parts = [
    page.h1,
    page.lead,
    page.ctaTitle,
    page.ctaText,
    page.faqTitle,
    ...page.sections.flatMap((section) => [
      section.title,
      ...section.paragraphs,
      ...(section.bullets ?? []),
    ]),
    ...page.faq.flatMap((item) => [item.question, item.answer]),
  ];
  return parts.reduce((sum, part) => sum + words(part), 0);
}

export function assertLandingCopy(): void {
  const seen = new Set<string>();
  for (const page of LANDINGS) {
    if (seen.has(page.path)) {
      throw new Error(`Повтор маршрута ${page.path}`);
    }
    seen.add(page.path);
    const count = landingWordCount(page);
    if (count < 600 || count > 1000) {
      throw new Error(`${page.path}: ${count} слов, нужно от 600 до 1000`);
    }
  }
}

export function getLanding(path: string): LandingPageData | undefined {
  return LANDINGS.find((page) => page.path === path);
}
